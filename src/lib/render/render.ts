let browserPromise: Promise<Browser> | null = null;
async function browser() {
  if (!browserPromise) {
    browserPromise = import("playwright").then(({ chromium }) =>
      chromium.launch({ args: ["--no-sandbox"], ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) }),
    );
    browserPromise.catch(() => (browserPromise = null));
  }
  return browserPromise;
}
export async function closeBrowser() {
  if (browserPromise) {
    const b = await browserPromise.catch(() => null);
    browserPromise = null;
    await b?.close();
  }
}

/** Renders one HTML page to a PNG of exactly width×height. */
export async function htmlToPng(html: string, width: number, height: number) {
  const b = await browser();
  const page = await b.newPage({ viewport: { width, height }, deviceScaleFactor: 1 });
  try {
    // Google Fonts may be unreachable (offline): never wait forever, fall back to system fonts.
    await page.route("**/*", (route) => {
      const url = route.request().url();
      if (url.startsWith("data:") || url.startsWith("https://fonts.googleapis.com/") || url.startsWith("https://fonts.gstatic.com/") || url === "about:blank") return route.continue();
      return route.abort();
    });
    await page.setContent(html, { waitUntil: "domcontentloaded", timeout: 30_000 });
    await page.waitForFunction(() => document.body.dataset.ready === "1", null, { timeout: 15_000 }).catch(() => undefined);
    return await page.screenshot({ type: "png", clip: { x: 0, y: 0, width, height } });
  } finally {
    await page.close();
  }
}

const dataUrl = (mime: string, bytes: Buffer) => `data:${mime};base64,${bytes.toString("base64")}`;

type BrandKit = Pick<LayoutInput, "colours" | "fonts" | "brandName" | "logoUrl" | "testLabel">;

/** Brand colours, fonts and logo from the approved Brand Brain (with neutral fallbacks). */
export async function brandKit(scope: BrandScope, brand: Brand): Promise<BrandKit> {
  const [visual] = await listEntries(scope, { section: "visual", status: "approved" });
  const files = await brandFiles(scope);
  const colours = ((visual?.data.colours as { hex: string }[]) ?? []).map((c) => c.hex);
  const logo = files.find((f) => f.kind === "logo");
  const fonts = files.filter((f) => f.kind === "font");
  const storage = getStorage();
  return {
    brandName: brand.name,
    testLabel: brand.isTest,
    colours: { primary: colours[0] ?? "#1F2937", secondary: colours[1] ?? "#F3F4F6", accent: colours[2] ?? colours[1] ?? "#F59E0B" },
    fonts: {
      heading: String(visual?.data.headingFont || "Inter"),
      body: String(visual?.data.bodyFont || "Inter"),
      faces: await Promise.all(fonts.map(async (f) => ({ family: String(f.meta.family ?? f.fileName.replace(/\.[^.]+$/, "")), url: dataUrl(f.mimeType, await storage.get(f.storageKey)) }))),
    },
    logoUrl: logo ? dataUrl(logo.mimeType, await storage.get(logo.storageKey)) : null,
  };
}

export type BackgroundChoice = { origin: "generated" | "brand_photo" | "plain"; asset: Asset | null; note?: string };

/**
 * Layer 1: the background. Generated by the image provider (one per post and size, reused for every language),
 * or an approved brand photo, or a plain brand-colour background. Never a stock or internet image.
 */
export async function backgroundFor(scope: BrandScope, brand: Brand, master: typeof masterPosts.$inferSelect, v: Variant, jobId: string | null, opts: { forceNew?: boolean } = {}): Promise<BackgroundChoice> {
  const wanted = (master.imageSource ?? brand.imageSource) as BackgroundChoice["origin"];
  const photos = (await brandFiles(scope)).filter((f) => f.kind === "photo" && f.meta.approved === true);
  const pickPhoto = (): BackgroundChoice | null => {
    if (!photos.length) return null;
    const h = createHash("md5").update(master.id).digest().readUInt32LE(0);
    return { origin: "brand_photo", asset: photos[h % photos.length] };
  };
  if (wanted === "plain") return { origin: "plain", asset: null };
  if (wanted === "brand_photo") return pickPhoto() ?? { origin: "plain", asset: null, note: "No approved brand photo yet: rendered on plain brand colour." };

  const provider = getImageProvider();
  if (!provider) {
    const fallback = pickPhoto();
    return fallback
      ? { ...fallback, note: "Image provider not connected: rendered on an approved brand photo." }
      : { origin: "plain", asset: null, note: "Image provider not connected and no approved brand photo: rendered on plain brand colour." };
  }
  if (!opts.forceNew) {
    const [existing] = await scope.select(
      assets,
      eq(assets.kind, "background"),
      sql`${assets.meta}->>'masterPostId' = ${master.id}`,
      sql`(${assets.meta}->>'width')::int = ${v.width}`,
      sql`(${assets.meta}->>'height')::int = ${v.height}`,
      sql`coalesce(${assets.meta}->>'superseded','false') = 'false'`,
    );
    if (existing) return { origin: "generated", asset: existing };
  }
  const prompt = v.visual?.imagePrompt ?? master.visualConcept;
  let lastErr: unknown;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const img = await provider.generateImage(prompt, { width: v.width, height: v.height });
      const key = brandKey(scope.brandId, "backgrounds", `${master.id}-${v.width}x${v.height}.png`);
      await getStorage().put(key, img.bytes);
      if (opts.forceNew)
        await scope.db
          .update(assets)
          .set({ meta: sql`${assets.meta} || '{"superseded":"true"}'::jsonb` })
          .where(scope.where(assets, eq(assets.kind, "background"), sql`${assets.meta}->>'masterPostId' = ${master.id}`, sql`(${assets.meta}->>'width')::int = ${v.width}`, sql`(${assets.meta}->>'height')::int = ${v.height}`));
      const [asset] = await scope.insert(assets, {
        kind: "background",
        fileName: `${master.date}-${v.width}x${v.height}.png`,
        storageKey: key,
        mimeType: img.mimeType,
        size: img.bytes.length,
        width: v.width,
        height: v.height,
        origin: "generated",
        meta: { masterPostId: master.id, width: v.width, height: v.height, prompt, model: img.model },
      });
      await scope.insert(usageRecords, { jobId, kind: "image", provider: provider.name, model: img.model, units: 1, costUsd: img.costUsd.toFixed(6) });
      return { origin: "generated", asset };
    } catch (e) {
      lastErr = e;
      if (!(e instanceof ImageProviderError) || !e.retryable) break;
      await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
  throw lastErr;
}

/** Layer 2: the layout. Renders every image of a variant (carousel: one PNG per slide) and stores them as assets. */
export async function renderVariant(scope: BrandScope, brand: Brand, v: Variant, kit: BrandKit, jobId: string | null, opts: { newBackground?: boolean } = {}) {
  if (v.format === "video_storyboard") return null; // storyboards are text; never rendered as video
  if (!v.visual) throw new Error("Variant has no visual direction yet.");
  const master = await scope.get(masterPosts, v.masterPostId);
  const bg = await backgroundFor(scope, brand, master, v, jobId, { forceNew: opts.newBackground });
  const storage = getStorage();
  const bgUrl = bg.asset ? dataUrl(bg.asset.mimeType, await storage.get(bg.asset.storageKey)) : null;
  const slides = v.visual.layout === "carousel" && (v.copy.slides?.length ?? 0) > 1 ? v.copy.slides! : null;
  const pages: LayoutInput[] = slides
    ? slides.map((s, i) => ({ ...kit, layout: "carousel", width: v.width, height: v.height, headline: v.visual!.headline, subtext: v.visual!.subtext, textPlacement: v.visual!.textPlacement, slide: { index: i, total: slides.length, heading: s.heading, body: s.body }, backgroundUrl: i === 0 ? bgUrl : null }))
    : [
        {
          ...kit,
          layout: (v.visual.layout === "carousel" ? "bold_headline" : v.visual.layout) as LayoutId,
          width: v.width,
          height: v.height,
          headline: v.visual.headline,
          subtext: v.visual.subtext,
          textPlacement: v.visual.textPlacement,
          points: v.copy.slides?.map((s) => s.heading) ?? v.copy.caption.split("\n").filter((l) => /^\s*(?:[-•*]|\d+[.)])\s+/.test(l)).map((l) => l.replace(/^\s*(?:[-•*]|\d+[.)])\s+/, "")),
          backgroundUrl: bgUrl,
        },
      ];
  const ids: string[] = [];
  for (const [i, page] of pages.entries()) {
    const png = await htmlToPng(layoutHtml(page), v.width, v.height);
    const key = brandKey(scope.brandId, `renders/${master.date}/${v.platform}`, `${v.language}-v${v.version}-${i + 1}.png`);
    await storage.put(key, png);
    const [a] = await scope.insert(assets, {
      kind: slides ? "slide" : "render",
      fileName: `${master.date}_${v.platform}_${v.language}_${String(i + 1).padStart(2, "0")}.png`,
      storageKey: key,
      mimeType: "image/png",
      size: png.length,
      width: v.width,
      height: v.height,
      variantId: v.id,
      variantVersion: v.version,
      slideIndex: i,
      origin: bg.origin,
      meta: { backgroundAssetId: bg.asset?.id ?? null, note: bg.note ?? null, layout: page.layout },
    });
    ids.push(a.id);
  }
  await scope.update(postVariants, { status: v.status === "approved" ? "approved" : "rendered", renderError: bg.note ?? null, updatedAt: new Date() }, eq(postVariants.id, v.id));
  await scope.update(postVariantVersions, { assetIds: ids }, eq(postVariantVersions.variantId, v.id), eq(postVariantVersions.version, v.version));
  return { assetIds: ids, origin: bg.origin, note: bg.note };
}

/** Current rendered images of a variant (for its current version), in slide order. */
export async function variantImages(scope: BrandScope, v: Pick<Variant, "id" | "version">) {
  const rows = await scope.select(assets, eq(assets.variantId, v.id), eq(assets.variantVersion, v.version));
  return rows.filter((a) => a.kind === "render" || a.kind === "slide").sort((a, b) => (a.slideIndex ?? 0) - (b.slideIndex ?? 0));
}

/** Renders every image variant of a post that has no image for its current version yet. */
export async function renderPost(scope: BrandScope, brand: Brand, masterId: string, jobId: string | null) {
  const variants = await postVariantsOf(scope, masterId);
  const kit = await brandKit(scope, brand);
  const errors: string[] = [];
  for (const v of variants) {
    if (v.format === "video_storyboard") continue;
    if ((await variantImages(scope, v)).length) continue;
    try {
      await renderVariant(scope, brand, v, kit, jobId);
    } catch (e) {
      errors.push(`${v.platform}/${v.language}: ${(e as Error).message}`);
      await scope.update(postVariants, { renderError: (e as Error).message }, eq(postVariants.id, v.id));
    }
  }
  const after = await postVariantsOf(scope, masterId);
  const imageVariants = after.filter((v) => v.format !== "video_storyboard");
  const master = await scope.get(masterPosts, masterId);
  if (imageVariants.length && imageVariants.every((v) => v.status === "rendered" || v.status === "approved") && master.status === "draft")
    await scope.update(masterPosts, { status: "rendered", updatedAt: new Date() }, eq(masterPosts.id, masterId));
  if (errors.length) throw new Error(`Rendering failed for ${errors.join("; ")}`);
}

